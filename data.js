/* =========================
   ملء قائمة الولايات
========================= */

function loadWilayas(){

const select =
document.getElementById("wilaya");

if(!select)return;

select.innerHTML = `
<option value="">
📍 اختر الولاية
</option>
`;

Object.keys(wilayas).forEach(wilaya=>{

const option =
document.createElement("option");

option.value = wilaya;

option.textContent = wilaya;

select.appendChild(option);

});

}


/* =========================
   ملء المدن حسب الولاية
========================= */

function loadCities(){

const wilayaSelect =
document.getElementById("wilaya");

const citySelect =
document.getElementById("city");

if(!wilayaSelect || !citySelect)return;

const wilaya =
wilayaSelect.value;

citySelect.innerHTML = `
<option value="">
🏙️ اختر المدينة / البلدية
</option>
`;

if(!wilaya || !wilayas[wilaya])return;

wilayas[wilaya].forEach(city=>{

const option =
document.createElement("option");

option.value = city;

option.textContent = city;

citySelect.appendChild(option);

});

}


/* =========================
   تشغيل الولايات
========================= */

document.addEventListener(
"DOMContentLoaded",
function(){

loadWilayas();

}
);
